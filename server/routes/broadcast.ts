/**
 * Broadcast Routes
 *
 * GET  /api/broadcast/auth/status    — OAuth2 authorization state
 * POST /api/broadcast/auth/config    — set Client ID + Secret (saved to env/memory)
 * GET  /api/broadcast/auth/url       — get the Google consent URL
 * GET  /api/broadcast/auth/callback  — OAuth2 redirect handler (called by Google)
 * POST /api/broadcast/auth/revoke    — revoke authorization + delete saved tokens
 *
 * GET  /api/broadcast/status         — current broadcast lifecycle state
 * POST /api/broadcast/create         — create broadcast + stream, get RTMP URL
 * POST /api/broadcast/go-live        — transition broadcast → live
 * POST /api/broadcast/end            — transition broadcast → complete
 * GET  /api/broadcast/health         — YouTube stream health check
 * DELETE /api/broadcast              — delete current broadcast (cleanup)
 */

import { safeErrorMessage } from '../utils/error-response.js';
import { Router, type Request, type Response } from 'express';
import { youtubeAuthService } from '../services/youtube-auth.js';
import { youtubeBroadcastService } from '../services/youtube-broadcast.js';
import { rateLimit } from '../utils/rate-limit.js';

const router = Router();

// YouTube broadcast lifecycle is quota-expensive. Allow a healthy number of
// retries during a session start but block runaway loops (a misbehaving
// scheduler could otherwise burn the daily YouTube quota in minutes).
const broadcastWriteLimit = rateLimit({ keyPrefix: 'broadcast.write', max: 10, windowMs: 60_000 });

// ── Status ─────────────────────────────────────────────────────────────────────

router.get('/auth/status', async (_req: Request, res: Response) => {
  const channel = youtubeAuthService.isAuthorized
    ? await youtubeAuthService.fetchAuthorizedChannel().catch(() => null)
    : null;

  res.json({
    configured: youtubeAuthService.isConfigured,
    authorized: youtubeAuthService.isAuthorized,
    channel,   // { id, title, thumbnailUrl } or null
  });
});

// ── Configure credentials ──────────────────────────────────────────────────────

router.post('/auth/config', (req: Request, res: Response) => {
  const { clientId, clientSecret } = req.body as {
    clientId?: string;
    clientSecret?: string;
  };

  if (!clientId || !clientSecret) {
    res.status(400).json({ error: 'clientId and clientSecret are required' });
    return;
  }

  const port        = process.env.PORT || '3001';
  const redirectUri = `http://localhost:${port}/api/broadcast/auth/callback`;

  youtubeAuthService.configure(clientId, clientSecret, redirectUri);

  res.json({
    ok:      true,
    authUrl: youtubeAuthService.getAuthUrl(),
  });
});

// ── Get auth URL ───────────────────────────────────────────────────────────────

router.get('/auth/url', (_req: Request, res: Response) => {
  if (!youtubeAuthService.isConfigured) {
    res.status(400).json({ error: 'OAuth credentials not configured — POST /api/broadcast/auth/config first' });
    return;
  }
  res.json({ url: youtubeAuthService.getAuthUrl() });
});

// ── OAuth2 callback ────────────────────────────────────────────────────────────

router.get('/auth/callback', async (req: Request, res: Response) => {
  const { code, error, state } = req.query as { code?: string; error?: string; state?: string };

  if (error) {
    res.send(callbackPage(
      false,
      `Authorization denied: ${error}`,
      'You can close this tab and return to Claw DJ.'
    ));
    return;
  }

  if (!code) {
    res.status(400).send(callbackPage(false, 'No authorization code received.', ''));
    return;
  }

  // CSRF: `state` was generated by getAuthUrl() and must round-trip exactly.
  // Single-use, 5-minute expiry. Without this, an attacker can trick the
  // owner into completing an OAuth flow they didn't initiate, binding the
  // attacker's intended account on the owner's machine.
  if (!youtubeAuthService.verifyState(state)) {
    res.status(400).send(callbackPage(
      false,
      'Authorization state mismatch.',
      'This usually means the auth URL expired (5 min) or the flow was started from a different session. Restart auth from the dashboard.'
    ));
    return;
  }

  try {
    await youtubeAuthService.handleCallback(code);
    res.send(callbackPage(
      true,
      'YouTube account authorized',
      'Claw DJ can now create and manage live broadcasts on your channel. You can close this tab.'
    ));
  } catch (err) {
    console.error('[Broadcast] OAuth callback error:', err);
    res.status(500).send(callbackPage(
      false,
      'Authorization failed',
      safeErrorMessage(err)
    ));
  }
});

// ── Revoke ─────────────────────────────────────────────────────────────────────

router.post('/auth/revoke', async (_req: Request, res: Response) => {
  try {
    await youtubeAuthService.revoke();
    res.json({ ok: true });
  } catch (err) {
    console.error('[Broadcast] Revoke error:', err);
    res.status(500).json({ error: safeErrorMessage(err) });
  }
});

