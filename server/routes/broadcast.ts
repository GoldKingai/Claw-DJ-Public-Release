// ── Broadcast lifecycle ─────────────────────────────────────────────────────────

router.get('/status', (_req: Request, res: Response) => {
  res.json(youtubeBroadcastService.info);
});

router.post('/create', broadcastWriteLimit, async (req: Request, res: Response) => {
  const { title, description, scheduledStartTime } = req.body as {
    title?: string;
    description?: string;
    scheduledStartTime?: string;
  };

  if (!title) {
    res.status(400).json({ error: 'title is required' });
    return;
  }

  if (!youtubeAuthService.isAuthorized) {
    res.status(401).json({ error: 'Not authorized — complete OAuth2 flow first' });
    return;
  }

  try {
    const info = await youtubeBroadcastService.createBroadcast(title, description, scheduledStartTime);
    res.json(info);
  } catch (err) {
    console.error('[Broadcast] Create error:', err);
    res.status(500).json({ error: safeErrorMessage(err) });
  }
});

router.post('/go-live', broadcastWriteLimit, async (_req: Request, res: Response) => {
  if (!youtubeAuthService.isAuthorized) {
    res.status(401).json({ error: 'Not authorized' });
    return;
  }

  try {
    await youtubeBroadcastService.goLive();
    res.json({ ok: true, status: 'live' });
  } catch (err) {
    console.error('[Broadcast] Go-live error:', err);
    res.status(500).json({ error: safeErrorMessage(err) });
  }
});

router.post('/end', async (_req: Request, res: Response) => {
  if (!youtubeAuthService.isAuthorized) {
    res.status(401).json({ error: 'Not authorized' });
    return;
  }

  try {
    await youtubeBroadcastService.endStream();
    res.json({ ok: true, status: 'complete' });
  } catch (err) {
    console.error('[Broadcast] End error:', err);
    res.status(500).json({ error: safeErrorMessage(err) });
  }
});

router.get('/health', async (_req: Request, res: Response) => {
  try {
    const health = await youtubeBroadcastService.getStreamHealth();
    res.json({ health });
  } catch (err) {
    res.status(500).json({ error: safeErrorMessage(err) });
  }
});

router.delete('/', async (_req: Request, res: Response) => {
  try {
    await youtubeBroadcastService.deleteBroadcast();
    res.json({ ok: true });
  } catch (err) {
    res.status(500).json({ error: safeErrorMessage(err) });
  }
});

export default router;
